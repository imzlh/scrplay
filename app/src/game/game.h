#ifndef SC_GAME_H
#define SC_GAME_H

#include "common.h"

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "game_engine.h"
#include "game_direct_touch.h"
#include "game_profile.h"
#include "game_ui.h"
#include "trait/key_processor.h"
#include "trait/mouse_processor.h"
#include "util/tick.h"

#define SC_GAME_PROFILES_DIR_LEN 512

enum sc_game_mode {
    SC_GAME_MODE_PLAY,
    SC_GAME_MODE_EDIT,
};

// The editor state is independent from the active input path. Native runtime
// delegates to the processors selected by regular scrplay options; mapped
// runtime uses the current game preset.
enum sc_game_runtime {
    SC_GAME_RUNTIME_MAPPED,
    SC_GAME_RUNTIME_NATIVE,
};

enum sc_game_save_status {
    SC_GAME_SAVE_STATUS_SAVED,
    // Includes the debounce interval: changes are waiting to be saved.
    SC_GAME_SAVE_STATUS_SAVING,
    SC_GAME_SAVE_STATUS_ERROR,
};

enum sc_game_binding_slot {
    SC_GAME_BINDING_NONE,
    SC_GAME_BINDING_JOYSTICK_UP,
    SC_GAME_BINDING_JOYSTICK_DOWN,
    SC_GAME_BINDING_JOYSTICK_LEFT,
    SC_GAME_BINDING_JOYSTICK_RIGHT,
    SC_GAME_BINDING_BIND,
    SC_GAME_BINDING_SWIPE,
};

// Game mode: a key/mouse processor pair wrapping the real processors, an
// injection engine and an ImGui-driven UI. When game mode is disabled, scrplay
// behaves exactly like upstream.
struct sc_game {
    struct sc_key_processor kp_trait; // exposed to sc_screen
    struct sc_mouse_processor mp_trait; // exposed to sc_screen
    struct sc_key_processor *real_kp; // may be NULL (--keyboard=disabled)
    struct sc_mouse_processor *real_mp; // may be NULL (--mouse=disabled)

    struct sc_controller *controller;
    struct sc_screen *screen; // NULL until sc_game_set_screen()

    struct sc_game_engine engine;
    struct sc_game_ui ui;

    struct sc_game_profile profile; // working copy (edited by the UI)
    // Incremented when the whole working profile is replaced (load/create).
    // The UI uses it to distinguish a profile switch from an in-place edit.
    uint64_t profile_revision;
    bool profile_loaded;
    bool profile_dirty;
    enum sc_game_save_status save_status;
    sc_tick autosave_deadline;
    bool engine_initialized;
    bool picker_blocking;
    // Stable coordinates into the profile, never a pointer invalidated by
    // preset/element memmove or whole-profile replacement.
    enum sc_game_binding_slot binding_slot;
    size_t binding_preset;
    size_t binding_element;

    enum sc_game_mode mode;
    enum sc_game_runtime runtime;
    // bit 0 = LAlt, bit 1 = RAlt; mapped play stays free until both are up
    uint8_t alt_pressed;
    // Alt+left mouse owns an absolute Android finger independently from the
    // relative game engine, so releasing Alt before the button cannot lose UP.
    struct sc_game_direct_touch direct_touch;
    // Capture keys configured by regular scrplay, restored in native runtime.
    uint16_t native_mouse_capture_keys;
    SDL_Keycode consumed_hotkey; // consume the matching key-up as well
    bool hotkey_text_pending; // suppress TEXTINPUT generated by a hotkey
    bool preset_hotkey_held;
    bool preset_hotkey_long_triggered;
    sc_tick preset_hotkey_deadline;
    // Keys whose DOWN was consumed by the mapping engine. Kept outside the
    // engine so their UP stays consumed even after capture/profile releases.
    uint32_t mapped_keys[SC_GAME_MAX_PRESSED_KEYS];
    size_t mapped_key_count;

    char profiles_dir[SC_GAME_PROFILES_DIR_LEN];
    char font_path[512];
    char ini_path[512];
    float ui_scale; // additional scale for the UI on HiDPI desktops (1 = auto
                    // detection disabled by --game-ui-scale)
};

// real_kp/real_mp: the processors selected by --keyboard/--mouse (either may
// be NULL). profile_name: profile to load (NULL/empty: auto-select, possibly
// opening the in-window picker). font_path: TTF font override (may be NULL).
bool
sc_game_init(struct sc_game *game, struct sc_controller *controller,
             struct sc_key_processor *real_kp,
             struct sc_mouse_processor *real_mp, const char *profile_name,
             const char *font_path, float ui_scale_override);

// Must be called once the screen is initialized (before the event loop
// starts). Installs the overlay render callback on the screen display.
bool
sc_game_set_screen(struct sc_game *game, struct sc_screen *screen);

void
sc_game_destroy(struct sc_game *game);

// SDL event pre-hook, called before sc_screen_handle_event(). Returns true if
// the event is consumed.
bool
sc_game_handle_event(struct sc_game *game, const SDL_Event *event);

// --- mode and profile management (also used by the UI) ---

void
sc_game_set_mode(struct sc_game *game, enum sc_game_mode mode);

void
sc_game_toggle_mode(struct sc_game *game);

bool
sc_game_is_native(const struct sc_game *game);

// Select a mapped preset without persisting runtime state in the profile.
bool
sc_game_select_preset(struct sc_game *game, size_t preset);

// Select regular scrplay input handling. The last mapped preset is retained.
void
sc_game_select_native(struct sc_game *game);

// Apply the working profile to the engine (called after edits).
void
sc_game_apply_profile(struct sc_game *game);

bool
sc_game_save_profile(struct sc_game *game);

// Schedule a debounced automatic save after an editor mutation.
void
sc_game_mark_profile_dirty(struct sc_game *game);

enum sc_game_save_status
sc_game_get_save_status(const struct sc_game *game);

// Load profile <name> from the profiles directory. Returns false on any
// storage or validation error; the caller may then present the picker.
bool
sc_game_load_profile(struct sc_game *game, const char *name);

// Create a profile with default content and load it. Existing files are never
// replaced: creating a configuration must not silently destroy another one.
bool
sc_game_create_profile(struct sc_game *game, const char *name);

// Return true when a valid profile with this exact name already exists.
bool
sc_game_profile_exists(struct sc_game *game, const char *name);

void
sc_game_delete_profile(struct sc_game *game, const char *name);

// Editor helper: arm the given key slot; the next keyboard key or mouse
// button press assigns it.
void
sc_game_arm_binding(struct sc_game *game, struct sc_game_key *key);

// Cancel an in-progress binding before changing preset/element structure.
void
sc_game_cancel_binding(struct sc_game *game);

bool
sc_game_is_binding_target(const struct sc_game *game,
                          const struct sc_game_key *key);

// List profile names present in the profiles directory. Returns the count.
size_t
sc_game_list_profiles(struct sc_game *game,
                      char names[][SC_GAME_PROFILE_NAME_MAX], size_t max);

// --- capture (HUD buttons) ---

void
sc_game_request_capture(struct sc_game *game, bool capture);

bool
sc_game_is_captured(struct sc_game *game);

#endif
